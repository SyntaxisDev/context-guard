"""Codex native mapping: tiers, agent TOML, skills, hooks.json and config.toml registrations."""

import copy
import difflib
import json
import re
import shlex
import tomllib
from functools import partial
from pathlib import Path

from core import render
from core.deadline import HOOK_TIMEOUT_SECONDS
from core.install_spec import InstallSpec, JsonMerge, TextEdit
from core.render import Agent, RenderedFile, RuntimeMapping

RUNTIME = "codex"
RUNTIME_NAME = "Codex"
CODEX_DIR = ".codex"
AGENTS_DIR = ".codex/agents"
SKILLS_DIR = ".codex/skills"
HOOK_SCRIPT = "adapters/codex/hooks.py"
SESSION_START = "SessionStart"
HOOK_EVENTS = (SESSION_START, "UserPromptSubmit", "PostToolUse", "Stop", "SubagentStop")
SECTION_BEGIN = (
    "# BEGIN context-guard agents (kit-owned; regenerated by context-guard install)"
)
SECTION_END = "# END context-guard agents"
SECTION = re.compile(
    re.escape(SECTION_BEGIN) + r"\n.*?" + re.escape(SECTION_END) + r"(?:\n|$)",
    re.DOTALL,
)
TABLE_HEADER = re.compile(r"^[ \t]*\[", re.MULTILINE)
OVERRIDE_SYNTAX = (
    "the `spawn_agent` `model` and `reasoning_effort` arguments. Always pass the role as "
    '`agent_type` and `fork_turns: "none"` so the subagent starts from your brief instead of '
    "the full chat history"
)
TRANSCRIPTS = "Codex keeps each session as a JSONL rollout under `~/.codex/sessions/<yyyy>/<mm>/<dd>/`."
ADVISORY_LIMITS = {
    "write": "Do not modify project files; write evidence only under /tmp.",
    "network": "Do not use network access (web requests, HTTP clients, package downloads).",
    "mcp": "Do not call MCP tools.",
    "git_push": "Do not push, and do not open or merge pull requests.",
}


def describe_tier(profile) -> str:
    return f"`{profile['model']}` with `{profile['effort']}` reasoning"


def toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def developer_instructions(agent: Agent) -> str:
    limits = [
        text
        for key, text in ADVISORY_LIMITS.items()
        if not agent.role.capabilities[key]
    ]
    if not limits:
        return agent.body.strip()
    lines = ["", "Role limits (Codex cannot enforce these for a role; follow them):"]
    return (
        agent.body.strip() + "\n" + "\n".join(lines + [f"- {text}" for text in limits])
    )


def render_agent(agent: Agent, profile) -> RenderedFile:
    """Only `features.shell_tool` restricts a Codex role; other capabilities are advisory text."""
    fields = {
        "name": agent.name,
        "description": agent.role.description,
        "model": profile["model"],
        "model_reasoning_effort": profile["effort"],
        "developer_instructions": developer_instructions(agent),
    }
    lines = [f"{key} = {toml_string(value)}" for key, value in fields.items()]
    if not agent.role.capabilities["shell"]:
        lines += ["", "[features]", "shell_tool = false"]
    text = "\n".join(lines) + "\n"
    try:
        tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        raise render.RenderError(
            f"agent {agent.name}: invalid TOML: {error}"
        ) from error
    return RenderedFile(f"{AGENTS_DIR}/{agent.name}.toml", text)


def enforced_limits(capabilities: dict) -> frozenset[str]:
    return frozenset() if capabilities["shell"] else frozenset({"shell"})


def runtime_mapping(config: dict) -> RuntimeMapping:
    return RuntimeMapping(
        runtime=RUNTIME,
        runtime_name=RUNTIME_NAME,
        handoff_dir=config["paths"]["handoff_dir"],
        tiers=config["tiers"],
        override_syntax=OVERRIDE_SYNTAX,
        transcripts=TRANSCRIPTS,
        channel="session_context",
        describe_tier=describe_tier,
        render_agent=render_agent,
        skills_dir=SKILLS_DIR,
        enforced_limits=enforced_limits,
    )


def policy_text(config: dict) -> str:
    return render.render_policy(runtime_mapping(config))


def hook_command(python: Path, kit: Path, event: str) -> str:
    return " ".join(
        shlex.quote(part) for part in (str(python), str(kit / HOOK_SCRIPT), event)
    )


def hook_handler(python: Path, kit: Path, event: str, context_limit: int) -> dict:
    handler = {
        "type": "command",
        "command": hook_command(python, kit, event),
        "timeout": HOOK_TIMEOUT_SECONDS,
    }
    if event == SESSION_START:
        handler["additionalContextLimit"] = context_limit
    return handler


def without_hooks(data: dict, drop) -> dict:
    """Remove handlers whose command matches `drop`, then empty groups and events."""
    result = copy.deepcopy(data)
    hooks = result.get("hooks", {})
    if not isinstance(hooks, dict):
        raise ValueError("hooks.json: `hooks` must be an object")
    for event, groups in list(hooks.items()):
        if not isinstance(groups, list):
            continue
        kept = []
        for group in groups:
            if isinstance(group, dict) and isinstance(group.get("hooks"), list):
                group["hooks"] = [
                    hook
                    for hook in group["hooks"]
                    if not (
                        isinstance(hook, dict) and drop(str(hook.get("command", "")))
                    )
                ]
                if not group["hooks"]:
                    continue
            kept.append(group)
        if kept:
            hooks[event] = kept
        else:
            del hooks[event]
    if "hooks" in result and not hooks:
        del result["hooks"]
    return result


def is_ours(kit: Path, command: str) -> bool:
    return str(kit / HOOK_SCRIPT) in command


def owned_groups(data: dict, drop) -> dict[str, list]:
    """Per event, the handler groups holding a handler whose command matches `drop`."""
    hooks = data.get("hooks", {})
    found = {}
    for event, groups in hooks.items() if isinstance(hooks, dict) else ():
        owned = [
            group
            for group in (groups if isinstance(groups, list) else [])
            if isinstance(group, dict)
            and isinstance(group.get("hooks"), list)
            and any(
                isinstance(hook, dict) and drop(str(hook.get("command", "")))
                for hook in group["hooks"]
            )
        ]
        if owned:
            found[event] = owned
    return found


def merge_hooks(data: dict, kit: Path, python: Path, context_limit: int) -> dict:
    """Register our handlers; a file already holding exactly them is returned as is (no reordering)."""
    drop = partial(is_ours, kit)
    expected = {
        event: [{"hooks": [hook_handler(python, kit, event, context_limit)]}]
        for event in HOOK_EVENTS
    }
    if owned_groups(data, drop) == expected:
        return data
    result = without_hooks(data, drop)
    hooks = result.setdefault("hooks", {})
    for event in HOOK_EVENTS:
        groups = hooks.setdefault(event, [])
        if not isinstance(groups, list):
            raise ValueError(f"hooks.json: hooks.{event} must be a list")
        groups.append({"hooks": [hook_handler(python, kit, event, context_limit)]})
    return result


def unmerge_hooks(data: dict, kit: Path) -> dict:
    return without_hooks(data, partial(is_ours, kit))


def registration_section(home: Path, descriptions: dict[str, str]) -> str:
    lines = [SECTION_BEGIN]
    for name, description in descriptions.items():
        lines += [
            f"[agents.{name}]",
            f"description = {toml_string(description)}",
            f"config_file = {toml_string(str(home / AGENTS_DIR / f'{name}.toml'))}",
            "",
        ]
    return "\n".join(lines[:-1] + [SECTION_END]) + "\n"


def evict_foreign_tables(text: str, names) -> str:
    """Codex rewrites config.toml itself and inserts new tables (trust, tui) before the trailing END marker."""
    match = SECTION.search(text)
    if match is None:
        return text
    body = match[0][len(SECTION_BEGIN) + 1 :].rstrip("\n").removesuffix(SECTION_END)
    starts = [header.start() for header in TABLE_HEADER.finditer(body)]
    ours, foreign = [body[: starts[0]] if starts else body], []
    for start, end in zip(starts, starts[1:] + [len(body)]):
        chunk = body[start:end]
        owned = chunk.split("\n", 1)[0].strip() in {
            f"[agents.{name}]" for name in names
        }
        (ours if owned else foreign).append(chunk)
    if not foreign:
        return text
    section = f"{SECTION_BEGIN}\n{''.join(ours).rstrip('\n')}\n{SECTION_END}\n"
    return (
        text[: match.start()]
        + section
        + "\n"
        + "".join(foreign).rstrip("\n")
        + "\n"
        + text[match.end() :]
    )


def remove_section(text: str) -> str:
    """A section ending the file without a newline was appended to a file that had none."""
    match = SECTION.search(text)
    if match is None:
        return text
    before = text[: match.start()]
    if before.endswith("\n\n"):
        before = before[:-1] if match[0].endswith("\n") else before[:-2]
    return before + text[match.end() :]


def parse_toml(text: str, label: str) -> dict:
    try:
        return tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        raise ValueError(f"config.toml {label} is not valid TOML: {error}") from error


def unrelated_settings(parsed: dict, names) -> dict:
    result = dict(parsed)
    agents = result.get("agents")
    if isinstance(agents, dict):
        result["agents"] = {
            name: value for name, value in agents.items() if name not in names
        }
        if not result["agents"]:
            del result["agents"]
    return result


def check_registrations(original: str, result: str, names) -> None:
    before = parse_toml(remove_section(original), "outside the context-guard section")
    agents = before.get("agents", {})
    taken = sorted(
        name for name in names if isinstance(agents, dict) and name in agents
    )
    if taken:
        raise ValueError(
            f"config.toml already defines [agents.{taken[0]}] outside the context-guard section"
        )
    after = parse_toml(result, "after registering context-guard agents")
    if unrelated_settings(before, names) != unrelated_settings(
        parse_toml(original, "before install"), names
    ) or unrelated_settings(after, names) != unrelated_settings(before, names):
        raise ValueError(
            "config.toml: the context-guard section holds other settings; move them outside "
            f"the `{SECTION_BEGIN}` markers"
        )


def apply_section(text: str, section: str, names) -> str:
    """A file without a final newline keeps none: the section then ends it without one."""
    text = evict_foreign_tables(text, names)
    match = SECTION.search(text)
    if match is not None:
        result = (
            text[: match.start()]
            + (section if match[0].endswith("\n") else section[:-1])
            + text[match.end() :]
        )
    elif text and not text.endswith("\n"):
        result = text + "\n\n" + section[:-1]
    else:
        result = text + ("\n" if text else "") + section
    check_registrations(text, result, names)
    return result


def section_diff(actual: str, expected: str, path: str) -> str:
    return "".join(
        difflib.unified_diff(
            expected.splitlines(keepends=True),
            actual.splitlines(keepends=True),
            f"{path} (generated)",
            f"{path} (current)",
        )
    )


def revert_section(text: str, section: str, names) -> str:
    text = evict_foreign_tables(text, names)
    match = SECTION.search(text)
    if match is None:
        return text
    actual = match[0] if match[0].endswith("\n") else match[0] + "\n"
    if actual != section:
        raise ValueError(
            "config.toml context-guard section was edited:\n"
            + section_diff(actual, section, "config.toml")
        )
    return remove_section(text)


def role_descriptions(mapping: RuntimeMapping) -> dict[str, str]:
    return {agent.name: agent.role.description for agent in render.agents(mapping)}


def install_spec(home: Path, kit: Path, python: Path, config: dict) -> InstallSpec:
    mapping = runtime_mapping(config)
    codex = home / CODEX_DIR
    descriptions = role_descriptions(mapping)
    section = registration_section(home, descriptions)
    return InstallSpec(
        runtime=RUNTIME,
        files={
            home / rendered.path: rendered.text
            for rendered in render.rendered_files(mapping)
        },
        json_merges=[
            JsonMerge(
                codex / "hooks.json",
                partial(
                    merge_hooks,
                    kit=kit,
                    python=python,
                    context_limit=config["additional_context_limit"],
                ),
                partial(unmerge_hooks, kit=kit),
            )
        ],
        text_edits=[
            TextEdit(
                codex / "config.toml",
                partial(apply_section, section=section, names=descriptions),
                partial(revert_section, section=section, names=descriptions),
            )
        ],
    )
