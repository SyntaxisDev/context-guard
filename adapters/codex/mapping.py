"""Codex native mapping: tiers, agent TOML, skills, hooks.json and config.toml registrations."""

import difflib
import json
import re
import tomllib
from collections.abc import Collection, Mapping
from functools import partial
from pathlib import Path

from core import hookfile, render
from core.deadline import HOOK_TIMEOUT_SECONDS
from core.install_spec import InstallSpec, TextEdit
from core.render import Agent, RenderedFile, RuntimeMapping

RUNTIME = "codex"
RUNTIME_NAME = "Codex"
CODEX_DIR = ".codex"
AGENTS_DIR = ".codex/agents"
SKILLS_DIR = ".codex/skills"
HOOK_SCRIPT = "adapters/codex/hooks.py"
SESSION_START = "SessionStart"
HOOK_EVENTS = (SESSION_START, "UserPromptSubmit", "PostToolUse", "Stop")
SECTION_BEGIN = "# BEGIN context-guard agents (kit-owned; regenerated by context-guard install)"
SECTION_END = "# END context-guard agents"
SECTION = re.compile(
    re.escape(SECTION_BEGIN) + r"\n.*?" + re.escape(SECTION_END) + r"(?:\n|$)",
    re.DOTALL,
)
TABLE_HEADER = re.compile(r"^[ \t]*\[", re.MULTILINE)
OVERRIDE_SYNTAX = (
    "the `spawn_agent` `model` and `reasoning_effort` arguments. Always pass the role as "
    '`agent_type` and `fork_turns: "none"` so the subagent starts from your brief instead of '
    "the full chat history"
)
TRANSCRIPTS = "Codex keeps each session as a JSONL rollout under `~/.codex/sessions/<yyyy>/<mm>/<dd>/`."
ADVISORY_LIMITS = {
    "write": "Do not modify project files; write evidence only under /tmp.",
    "network": "Do not use network access (web requests, HTTP clients, package downloads).",
    "mcp": "Do not call MCP tools.",
    "git_push": "Do not push, and do not open or merge pull requests.",
}


def describe_tier(profile: Mapping[str, str]) -> str:
    """Describe a tier for the policy's tier table.

    Args:
        profile: Tier profile with `model` and `effort`.

    Returns:
        Markdown naming the model and its reasoning effort.
    """
    return f"`{profile['model']}` with `{profile['effort']}` reasoning"


def toml_string(value: str) -> str:
    """Quote text as a TOML basic string.

    Args:
        value: Text to quote.

    Returns:
        The quoted string; JSON escapes are valid TOML basic-string escapes.
    """
    return json.dumps(value, ensure_ascii=False)


def developer_instructions(agent: Agent) -> str:
    """Build a Codex agent's instructions: the role body plus the limits Codex cannot enforce.

    Args:
        agent: The role variant to render.

    Returns:
        The role body, followed by an advisory list of every capability the role lacks.
    """
    limits = [text for key, text in ADVISORY_LIMITS.items() if not agent.role.capabilities[key]]
    if not limits:
        return agent.body.strip()
    lines = ["", "Role limits (Codex cannot enforce these for a role; follow them):"]
    return agent.body.strip() + "\n" + "\n".join(lines + [f"- {text}" for text in limits])


def render_agent(agent: Agent, profile: Mapping[str, str]) -> RenderedFile:
    """Render a role as a Codex agent TOML file.

    Only `features.shell_tool` restricts a Codex role; other capabilities are advisory text.

    Args:
        agent: The role variant to render.
        profile: Tier profile with the `model` and `effort` the agent runs on.

    Returns:
        The agent TOML file under the agents directory.

    Raises:
        RenderError: The rendered text is not valid TOML.
    """
    fields = {
        "name": agent.name,
        "description": agent.role.description,
        "model": profile["model"],
        "model_reasoning_effort": profile["effort"],
        "developer_instructions": developer_instructions(agent),
    }
    lines = [f"{key} = {toml_string(value)}" for key, value in fields.items()]
    if not agent.role.capabilities["shell"]:
        lines += ["", "[features]", "shell_tool = false"]
    text = "\n".join(lines) + "\n"
    try:
        tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        msg = f"agent {agent.name}: invalid TOML: {error}"
        raise render.RenderError(msg) from error
    return RenderedFile(f"{AGENTS_DIR}/{agent.name}.toml", text)


def enforced_limits(capabilities: Mapping[str, bool]) -> frozenset[str]:
    """Name the capability limits Codex enforces for a role.

    Args:
        capabilities: The role's capability flags.

    Returns:
        `shell` for a role without shell, else nothing.
    """
    return frozenset() if capabilities["shell"] else frozenset({"shell"})


def runtime_mapping(config: dict) -> RuntimeMapping:
    """Describe Codex's rendering of the shared content.

    Args:
        config: Loaded Codex adapter configuration.

    Returns:
        The runtime mapping; the policy reaches Codex as session context, not as a file.
    """
    return RuntimeMapping(
        runtime=RUNTIME,
        runtime_name=RUNTIME_NAME,
        handoff_dir=config["paths"]["handoff_dir"],
        tiers=config["tiers"],
        override_syntax=OVERRIDE_SYNTAX,
        transcripts=TRANSCRIPTS,
        channel="session_context",
        describe_tier=describe_tier,
        render_agent=render_agent,
        skills_dir=SKILLS_DIR,
        enforced_limits=enforced_limits,
    )


def policy_text(config: dict) -> str:
    """Render the Codex policy that SessionStart injects.

    Args:
        config: Loaded Codex adapter configuration.

    Returns:
        The rendered policy markdown.
    """
    return render.render_policy(runtime_mapping(config))


def hook_groups(python: Path, kit: Path, context_limit: int) -> dict[str, dict]:
    """Build the hooks.json handler group of every registered event.

    Args:
        python: Interpreter that runs the hook script.
        kit: Installed kit root holding the hook script.
        context_limit: `additionalContextLimit` for SessionStart, in characters.

    Returns:
        One group with one command handler per native event.
    """
    groups = {}
    for event in HOOK_EVENTS:
        handler = {
            "type": "command",
            "command": hookfile.hook_command(python, kit / HOOK_SCRIPT, event),
            "timeout": HOOK_TIMEOUT_SECONDS,
        }
        if event == SESSION_START:
            handler["additionalContextLimit"] = context_limit
        groups[event] = {"hooks": [handler]}
    return groups


def registration_section(home: Path, descriptions: dict[str, str]) -> str:
    """Render the kit-owned config.toml section that registers our agents.

    Args:
        home: Home directory the agent files are installed under.
        descriptions: Description per agent name.

    Returns:
        The marked section, ending with a newline.
    """
    lines = [SECTION_BEGIN]
    for name, description in descriptions.items():
        lines += [
            f"[agents.{name}]",
            f"description = {toml_string(description)}",
            f"config_file = {toml_string(str(home / AGENTS_DIR / f'{name}.toml'))}",
            "",
        ]
    return "\n".join([*lines[:-1], SECTION_END]) + "\n"


def evict_foreign_tables(text: str, names: Collection[str]) -> str:
    """Move tables Codex inserted inside our section to just after it.

    Codex rewrites config.toml itself and inserts new tables (trust, tui) before the trailing END marker.

    Args:
        text: Current config.toml text.
        names: Our agent names; only their `[agents.<name>]` tables stay in the section.

    Returns:
        The text with foreign tables after the section, or unchanged when there are none.
    """
    match = SECTION.search(text)
    if match is None:
        return text
    body = match[0][len(SECTION_BEGIN) + 1 :].rstrip("\n").removesuffix(SECTION_END)
    starts = [header.start() for header in TABLE_HEADER.finditer(body)]
    ours, foreign = [body[: starts[0]] if starts else body], []
    for start, end in zip(starts, [*starts[1:], len(body)], strict=True):
        chunk = body[start:end]
        owned = chunk.split("\n", 1)[0].strip() in {f"[agents.{name}]" for name in names}
        (ours if owned else foreign).append(chunk)
    if not foreign:
        return text
    section = f"{SECTION_BEGIN}\n{''.join(ours).rstrip('\n')}\n{SECTION_END}\n"
    return text[: match.start()] + section + "\n" + "".join(foreign).rstrip("\n") + "\n" + text[match.end() :]


def remove_section(text: str) -> str:
    """Remove our section and the blank line that separated it.

    A section ending the file without a newline was appended to a file that had none.

    Args:
        text: config.toml text.

    Returns:
        The text without the section, or unchanged when it has none.
    """
    match = SECTION.search(text)
    if match is None:
        return text
    before = text[: match.start()]
    if before.endswith("\n\n"):
        before = before[:-1] if match[0].endswith("\n") else before[:-2]
    return before + text[match.end() :]


def parse_toml(text: str, label: str) -> dict:
    """Parse config.toml text.

    Args:
        text: TOML text.
        label: Which version of the file this is, for the error message.

    Returns:
        The parsed document.

    Raises:
        ValueError: The text is not valid TOML.
    """
    try:
        return tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        msg = f"config.toml {label} is not valid TOML: {error}"
        raise ValueError(msg) from error


def unrelated_settings(parsed: dict, names: Collection[str]) -> dict:
    """Drop our agent registrations from a parsed config.toml.

    Args:
        parsed: Parsed config.toml; it is not modified.
        names: Our agent names.

    Returns:
        A shallow copy without `[agents.<name>]` for our names, and without an emptied `agents`.
    """
    result = dict(parsed)
    agents = result.get("agents")
    if isinstance(agents, dict):
        result["agents"] = {name: value for name, value in agents.items() if name not in names}
        if not result["agents"]:
            del result["agents"]
    return result


def check_registrations(original: str, result: str, names: Collection[str]) -> None:
    """Check that registering our section changes nothing but our agents.

    Invalid TOML in either text raises ValueError from `parse_toml`.

    Args:
        original: config.toml before the edit.
        result: config.toml after the edit.
        names: Our agent names.

    Raises:
        ValueError: One of our names is already defined outside the section, or the section
            holds other settings.
    """
    before = parse_toml(remove_section(original), "outside the context-guard section")
    agents = before.get("agents", {})
    taken = sorted(name for name in names if isinstance(agents, dict) and name in agents)
    if taken:
        msg = f"config.toml already defines [agents.{taken[0]}] outside the context-guard section"
        raise ValueError(msg)
    after = parse_toml(result, "after registering context-guard agents")
    if unrelated_settings(before, names) != unrelated_settings(
        parse_toml(original, "before install"), names
    ) or unrelated_settings(after, names) != unrelated_settings(before, names):
        msg = (
            "config.toml: the context-guard section holds other settings; move them outside "
            f"the `{SECTION_BEGIN}` markers"
        )
        raise ValueError(msg)


def apply_section(text: str, section: str, names: Collection[str]) -> str:
    """Write our section into config.toml text, replacing an existing one or appending it.

    A file without a final newline keeps none: the section then ends it without one. A
    conflicting registration raises ValueError from `check_registrations`.

    Args:
        text: Current config.toml text.
        section: The rendered registration section.
        names: Our agent names.

    Returns:
        The edited text.
    """
    text = evict_foreign_tables(text, names)
    match = SECTION.search(text)
    if match is not None:
        result = text[: match.start()] + (section if match[0].endswith("\n") else section[:-1]) + text[match.end() :]
    elif text and not text.endswith("\n"):
        result = text + "\n\n" + section[:-1]
    else:
        result = text + ("\n" if text else "") + section
    check_registrations(text, result, names)
    return result


def section_diff(actual: str, expected: str, path: str) -> str:
    """Diff a generated section against its current text.

    Args:
        actual: The section as found in the file.
        expected: The section as generated.
        path: File name for the diff headers.

    Returns:
        A unified diff from generated to current.
    """
    return "".join(
        difflib.unified_diff(
            expected.splitlines(keepends=True),
            actual.splitlines(keepends=True),
            f"{path} (generated)",
            f"{path} (current)",
        )
    )


def revert_section(text: str, section: str, names: Collection[str]) -> str:
    """Remove our section from config.toml text on uninstall.

    Args:
        text: Current config.toml text.
        section: The section as the install generated it.
        names: Our agent names.

    Returns:
        The text without the section, or unchanged when it has none.

    Raises:
        ValueError: The section differs from the generated one, i.e. the user edited it.
    """
    text = evict_foreign_tables(text, names)
    match = SECTION.search(text)
    if match is None:
        return text
    actual = match[0] if match[0].endswith("\n") else match[0] + "\n"
    if actual != section:
        msg = "config.toml context-guard section was edited:\n" + section_diff(actual, section, "config.toml")
        raise ValueError(msg)
    return remove_section(text)


def role_descriptions(mapping: RuntimeMapping) -> dict[str, str]:
    """Collect the description of every rendered agent.

    Args:
        mapping: The Codex runtime mapping.

    Returns:
        Description per agent name.
    """
    return {agent.name: agent.role.description for agent in render.agents(mapping)}


def kit_signatures(home: Path, descriptions: dict[str, str]) -> dict[Path, tuple[str, ...]]:
    """Identify kit agent files that no manifest records.

    The body is one TOML string, so an unrecorded kit agent is known by its name and description lines.

    Args:
        home: Home directory the agent files are installed under.
        descriptions: Description per agent name.

    Returns:
        The lines that mark each agent file as the kit's.
    """
    return {
        home / AGENTS_DIR / f"{name}.toml": (
            f"name = {toml_string(name)}",
            f"description = {toml_string(description)}",
        )
        for name, description in descriptions.items()
    }


def install_spec(home: Path, kit: Path, python: Path, config: dict) -> InstallSpec:
    """Plan the Codex install: rendered files, the hooks.json merge and the config.toml section.

    Args:
        home: Home directory to install into.
        kit: Installed kit root.
        python: Interpreter that runs the hook script.
        config: Loaded Codex adapter configuration.

    Returns:
        The install spec for the shared installer.
    """
    mapping = runtime_mapping(config)
    codex = home / CODEX_DIR
    descriptions = role_descriptions(mapping)
    section = registration_section(home, descriptions)
    return InstallSpec(
        runtime=RUNTIME,
        files={home / rendered.path: rendered.text for rendered in render.rendered_files(mapping)},
        json_merges=[
            hookfile.group_merge(
                codex / "hooks.json",
                hook_groups(python, kit, config["hook_output"]["session_context_limit"]),
                kit / HOOK_SCRIPT,
            )
        ],
        text_edits=[
            TextEdit(
                codex / "config.toml",
                partial(apply_section, section=section, names=descriptions),
                partial(revert_section, section=section, names=descriptions),
            )
        ],
        kit_signatures=kit_signatures(home, descriptions),
    )
